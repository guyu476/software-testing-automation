-- ========== 3. 成绩表（中间表） ==========
CREATE TABLE scores (
    id         INT          NOT NULL AUTO_INCREMENT COMMENT '自增主键',
    student_id INT          NOT NULL COMMENT '学号，关联 students.student_id',
    course_id  VARCHAR(10)  NOT NULL COMMENT '课程编号，关联 courses.course_id',
    score      DECIMAL(4,1) NULL     COMMENT '分数，NULL 表示缺考',
    exam_date  DATE         NOT NULL COMMENT '考试日期',
    PRIMARY KEY (id),
    KEY idx_student (student_id),
    KEY idx_course (course_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='成绩表';

